cat > "$pkg/DEBIAN/control" <<EOF
Package: opencardshop
Version: $version
Architecture: all
Maintainer: $maintainer
Installed-Size: $(du -sk --exclude=DEBIAN "$pkg" | cut -f1)
Depends: python3 (>= 3.10), python3-tk, python3-pil (>= 9.0), python3-pil.imagetk, fonts-dejavu-core, fonts-liberation
Recommends: fontconfig, cups-client, xdg-utils
Suggests: p7zip-full, inkscape
Section: graphics
Priority: optional
Description: offline greeting-card designer with folded-card printing
 OpenCardShop designs, personalises and prints quarter-fold greeting cards on
 one side of a single A4, Letter or Legal sheet, with fold guides and a
 printer test sheet.
 .
 It includes an open starter pack of clipart, fonts, messages and ready-made
 cards, offers the fonts installed on the computer, and keeps each user's own
 pictures, messages and designs in a reusable "My library". It can also open
 CardShop Plus cards and content from the user's own CD, which is not included.
EOF
cat > "$pkg/DEBIAN/postinst" <<'EOF'
#!/bin/sh
set -e
if [ "$1" = configure ]; then
    python3 -m compileall -q /usr/share/opencardshop/main.py /usr/share/opencardshop/opencardshop >/dev/null 2>&1 || true
fi
EOF
cat > "$pkg/DEBIAN/prerm" <<'EOF'
#!/bin/sh
set -e
if [ "$1" = remove ] || [ "$1" = upgrade ] || [ "$1" = deconfigure ]; then
    find /usr/share/opencardshop -name __pycache__ -type d -prune -exec rm -rf {} + 2>/dev/null || true
fi
EOF
chmod 755 "$pkg/DEBIAN/postinst" "$pkg/DEBIAN/prerm"
(cd "$pkg" && find usr -type f -print0 | sort -z | xargs -0 md5sum > DEBIAN/md5sums)
chmod 644 "$pkg/DEBIAN/md5sums"

mkdir -p "$out"
dpkg-deb --root-owner-group -Zxz --build "$pkg" "$out/opencardshop_${version}_all.deb" >/dev/null
echo "Built $out/opencardshop_${version}_all.deb"
if command -v lintian >/dev/null; then lintian --no-tag-display-limit "$out/opencardshop_${version}_all.deb" || true; fi
