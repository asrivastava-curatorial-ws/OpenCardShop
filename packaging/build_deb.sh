#!/usr/bin/env bash
# Build dist/opencardshop_<version>_all.deb from this source tree.
# Needs: dpkg-deb, gzip, python3, Pillow (for the menu icon sizes). Optional: lintian.
# No CardShop Plus content is packaged: only the editor, the open starter pack,
# the fallback fonts and the icons.
set -euo pipefail
src="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
version="$(sed -n 's/^__version__ = "\(.*\)"$/\1/p' "$src/opencardshop/__init__.py")"
maintainer="${DEBFULLNAME:-Abhisht Srivastava} <${DEBEMAIL:-abhishtsrivastava@gmail.com}>"
out="${1:-$src/dist}"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
pkg="$work/opencardshop_${version}_all"
app="$pkg/usr/share/opencardshop"
doc="$pkg/usr/share/doc/opencardshop"

install -d "$app/assets" "$pkg/usr/bin" "$pkg/usr/share/applications" "$pkg/usr/share/mime/packages" \
           "$pkg/usr/share/man/man1" "$doc" "$pkg/DEBIAN"
install -m 644 "$src/main.py" "$app/"
cp -r "$src/opencardshop" "$app/"
cp -r "$src/assets/fallback_fonts" "$src/assets/starter" "$src/assets/icons" "$app/assets/"
find "$app" -name '__pycache__' -prune -exec rm -rf {} +
find "$app" -type d -exec chmod 755 {} + && find "$app" -type f -exec chmod 644 {} +
# Use Debian's own copies of the fallback fonts (fonts-dejavu-core, fonts-liberation).
for font in "$app"/assets/fallback_fonts/*.ttf; do
    name="$(basename "$font")"
    case "$name" in DejaVu*) family=dejavu ;; *) family=liberation ;; esac
    ln -sf "../../../fonts/truetype/$family/$name" "$font"
done
rm -f "$app"/assets/fallback_fonts/LICENSE-*.txt

cat > "$pkg/usr/bin/opencardshop" <<'EOF'
#!/bin/sh
# OpenCardShop launcher; set OPENCARDSHOP_PYTHON to use another interpreter.
exec "${OPENCARDSHOP_PYTHON:-/usr/bin/python3}" /usr/share/opencardshop/main.py "$@"
EOF
chmod 755 "$pkg/usr/bin/opencardshop"

install -m 644 "$src/packaging/linux/opencardshop.desktop" "$pkg/usr/share/applications/"
install -m 644 "$src/packaging/linux/opencardshop.xml" "$pkg/usr/share/mime/packages/"
sed "s/@VERSION@/$version/" "$src/packaging/linux/opencardshop.1" | gzip -9n > "$pkg/usr/share/man/man1/opencardshop.1.gz"
chmod 644 "$pkg/usr/share/man/man1/opencardshop.1.gz"
for size in 16 32 48 64 128 256; do
    install -d "$pkg/usr/share/icons/hicolor/${size}x${size}/apps"
    python3 -c 'import sys; from PIL import Image; Image.open(sys.argv[1]).convert("RGBA").resize((int(sys.argv[3]),) * 2, Image.LANCZOS).save(sys.argv[2], optimize=True)' \
        "$src/assets/icons/opencardshop.png" "$pkg/usr/share/icons/hicolor/${size}x${size}/apps/opencardshop.png" "$size"
    chmod 644 "$pkg/usr/share/icons/hicolor/${size}x${size}/apps/opencardshop.png"
done

install -m 644 "$src/README.md" "$src/NOTICE.md" "$src/docs/USER_GUIDE.md" "$doc/"
printf 'opencardshop (%s) unstable; urgency=medium\n\n  * Release %s. See /usr/share/doc/opencardshop/README.md.\n\n -- %s  %s\n' \
    "$version" "$version" "$maintainer" "$(date -R -u -d @"${SOURCE_DATE_EPOCH:-$(date +%s)}")" | gzip -9n > "$doc/changelog.gz"
chmod 644 "$doc/changelog.gz"
cat > "$doc/copyright" <<EOF
